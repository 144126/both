// The checker's own data: one small set of files the app downloads once and then reads only from the device.
// Usage: node pipeline/bundle.ts (after site.ts) -> site/static/app/<version>/, site/src/lib/bundle.ts (version and file list)
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { CLASSES } from './classes.ts';
import { members } from './resolve.ts';

const index = JSON.parse(readFileSync('site/static/api/v1/index.json', 'utf8'));
const pairs: [string, string, string, string, number[]][] = JSON.parse(readFileSync('data/out/pairs.json', 'utf8'));
const evidence = JSON.parse(readFileSync('data/out/evidence.json', 'utf8'));
const version: string = index.i;
const dir = `site/static/app/${version.replace(/[:]/g, '-')}`;
rmSync('site/static/app', { recursive: true, force: true });
mkdirSync(`${dir}/text`, { recursive: true });
const id = new Map((index.c as [string, string][]).map(([n], i) => [n, i]));
const SOURCES = Object.keys(index.s);
if (evidence.length > 65535 || index.c.length > 65535) throw new Error('ids no longer fit in 16 bits');

// pairs.bin (gzip), little-endian: header u32 [n, m]; a u16[n], b u16[n], sources u16[n] (bit per source code in index.s order),
// evidence ids u16[m] (strongest first, at most 5 per pair); severity u8[n] (index in "xacmn"), evidence count u8[n].
// 16-bit arrays come first so every one starts aligned.
const n = pairs.length, refs: number[] = [];
const a = new Uint16Array(n), b = new Uint16Array(n), s = new Uint8Array(n), r = new Uint16Array(n), k = new Uint8Array(n);
pairs.forEach(([x, y, sev, src, ev], i) => {
  a[i] = id.get(x)!; b[i] = id.get(y)!; s[i] = 'xacmn'.indexOf(sev);
  r[i] = src.split(',').reduce((m, c) => m | (1 << SOURCES.indexOf(c)), 0);
  const top = ev.slice(0, 5); k[i] = top.length; refs.push(...top);
});
const parts = [Uint32Array.of(n, refs.length), a, b, r, Uint16Array.from(refs), s, k];
const bin = Buffer.concat(parts.map(p => Buffer.from(p.buffer, p.byteOffset, p.byteLength)));
writeFileSync(`${dir}/pairs.bin.gz`, gzipSync(bin, { level: 9 }));

// evidence.json: [source, severity, source's words, via class, effects, raises, lowers] per evidence id
const ids = (list?: string[]) => (list ?? []).filter(x => id.has(x)).map(x => id.get(x)!);
writeFileSync(`${dir}/evidence.json`, JSON.stringify(evidence.map((e: Record<string, string & string[]>) => [e.r, e.s, e.o, e.c ?? '', e.f, ids(e.up), ids(e.dn)])));
// text/<k>.json: [text, patient text, link, title] for evidence ids k*1000 … k*1000+999
const CHUNK = 1000;
const cut = (t: string, m: number) => (t.length > m ? `${t.slice(0, m).replace(/\s+\S*$/, '')}…` : t);
for (let c = 0; c * CHUNK < evidence.length; c++)
  writeFileSync(`${dir}/text/${c}.json`, JSON.stringify(evidence.slice(c * CHUNK, (c + 1) * CHUNK).map((e: Record<string, string>) => [cut(e.t, 900), e.p ?? '', e.u, e.n])));
// index.json is the API index plus m: class ids of each drug, for the drug page
const classes = (index.c as [string, string][]).map(() => [] as string[]);
for (const c of Object.keys(CLASSES)) for (const m of members(c)) if (id.has(m)) classes[id.get(m)!].push(c);
writeFileSync(`${dir}/index.json`, JSON.stringify({ ...index, m: classes }));

const files = ['index.json', 'pairs.bin.gz', 'evidence.json', ...Array.from({ length: Math.ceil(evidence.length / CHUNK) }, (_, c) => `text/${c}.json`)];
writeFileSync('site/src/lib/bundle.ts', `// generated by pipeline/bundle.ts\nexport const VERSION = ${JSON.stringify(version)};\nexport const BASE = ${JSON.stringify(dir.replace('site/static', ''))};\nexport const FILES = ${JSON.stringify(files)};\nexport const PAIRS = ${n};\nexport const TEXT_CHUNK = ${CHUNK};\n`);
console.log(version, n, 'pairs,', refs.length, 'evidence refs,', files.length, 'files');
